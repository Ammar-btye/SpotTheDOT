"""Export the System 2 contract (analyst/contract.py) as committed JSON Schemas for web type generation. Run from
amd/system2:

    python scripts/export_schema.py                 # regenerate schema/*.json after a contract change
    python scripts/export_schema.py --check         # exit 1 if any committed schema drifted (T-01-14)

Writes schema/flag.schema.json, packet.schema.json, assess_request.schema.json and assess_response.schema.json.
Request-side models export in validation mode. The packet and the response export in serialization mode, so
response fields that have defaults are still marked required and the generated TypeScript types do not make them
optional. Keys are never sorted: property order is part of the contract (the Phase 2 grammar depends on it).
"""
import argparse
import json
import sys
from pathlib import Path
from typing import List

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from analyst.contract import CONTRACT_VERSION, ContextPacket, Flag  # noqa: E402
from analyst.backend_contract import (BACKEND_CONTRACT_VERSION, BackendAssessRequest,
                                     BackendAssessResponse)  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = (("flag.schema.json", Flag, "validation", CONTRACT_VERSION),
           ("packet.schema.json", ContextPacket, "serialization", CONTRACT_VERSION),
           ("assess_request.schema.json", BackendAssessRequest, "validation", BACKEND_CONTRACT_VERSION),
           ("assess_response.schema.json", BackendAssessResponse, "serialization", BACKEND_CONTRACT_VERSION))


def render(model, mode: str, version: str) -> str:
    source = model.__module__.replace(".", "/") + ".py"
    d = {"$comment": "Generated by amd/system2/scripts/export_schema.py from %s (contract %s). "
                     "Do not edit by hand." % (source, version)}
    d.update(model.model_json_schema(mode=mode))
    return json.dumps(d, indent=2, ensure_ascii=False) + "\n"


def export(out_dir: Path, check: bool) -> List[str]:
    """Names of schema files whose on-disk text differs from render(); writes them all unless check."""
    out_dir = Path(out_dir)
    if not check:
        out_dir.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, model, mode, version in SCHEMAS:
        text, p = render(model, mode, version), out_dir / name
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            stale.append(name)
        if not check:
            p.write_text(text, encoding="utf-8")
    return stale


def main():
    ap = argparse.ArgumentParser(description="Export analyst/contract.py as JSON Schema files.")
    ap.add_argument("--out", default=str(ROOT / "schema"))
    ap.add_argument("--check", action="store_true", help="compare only; exit 1 if any schema is stale")
    args = ap.parse_args()
    stale = export(Path(args.out), args.check)
    if args.check:
        if stale:
            print("stale: %s" % ", ".join(stale))
            sys.exit(1)
        print("%d schemas up to date" % len(SCHEMAS))
    else:
        print("wrote %d schemas to %s" % (len(SCHEMAS), args.out))


if __name__ == "__main__":
    main()
